// Furniture for the scene settings (#431, slice 1): pixel-string props baked into a setting's texture by
// render/interior.js. Drawn here by hand in the Eldmoor style (light from the top left: highlight up and left,
// shade down and right; the caller adds the dark outline). Wood, cloth and glass take the room's theme colours
// (render/palette.js THEMES), so one table reads as honey pine in a house and smoked oak in a tavern.
//
// FURN[kind] = {rows | make(w), map(theme) -> palette, ox, oy, light?}
//   ox, oy   pixel offset of the sprite's top left from its tile's top left (wall pieces: from the wall face tile,
//            which has the upper course of the wall above it, so a negative oy climbs the wall)
//   light    'warm' (fire, candle, lantern), 'day' (a window, the hatch) or 'crypt' (spirit fire)
// Sizes in tiles are the generator's (data/settings.js FOOT). Long pieces (benches, pews, long tables, the hold's
// ladder) are built by a function of their width so they need no hand-drawn copy per length.
