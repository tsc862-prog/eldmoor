// ---- built by width ----
function table(w){const top=['L'.repeat(w)],body=[];for(let r=0;r<5;r++)body.push('L'+(r===2?'G'.repeat(w-2):'M'.repeat(w-2))+'S');
  const leg='.DD'+'.'.repeat(w-6)+'DD.';return top.concat(body,['S'.repeat(w),'D'.repeat(w),leg,leg,leg,leg])}
function bench(w,back){const out=[];if(back){out.push('L'.repeat(w),'L'+'M'.repeat(w-2)+'S','S'.repeat(w))}
  out.push('L'.repeat(w),'L'+'M'.repeat(w-2)+'S','S'.repeat(w));const leg='.D'+'.'.repeat(w-4)+'D.';out.push(leg,leg,leg);return out}
function ladder(h){const out=[];for(let y=0;y<h;y++)out.push(y%5===2?'LMMMMMMMMMMS':'LS........LS');return out}
function rack(){const out=['L'.repeat(22)];for(let r=0;r<3;r++){out.push('L'+'D'.repeat(20)+'S');
    let a='L',b='L';for(let c=0;c<5;c++){const col=(r*5+c)%3===0?'G':'R';a+='D'+col.toLowerCase()+col+'D';b+='D'+col+col+'D'}out.push(a+'S',b+'S')}
  out.push('L'+'D'.repeat(20)+'S','S'.repeat(22));return out}

